-- Task Planner: лимит на хранилище фото задач (BAS-1442).
--
--   Портал сжимает каждое фото в JPEG до ~400 КБ перед загрузкой. Лимит в хранилище — защита
--   на случай, если сжатие обойдут или оно сломается: только JPEG, до 2 МБ на файл.
--   Уже загруженные файлы не трогаются (лимит действует на новые загрузки).
--
-- Применять: Supabase CLI. Идемпотентно.

update storage.buckets
   set file_size_limit = 2 * 1024 * 1024,
       allowed_mime_types = array['image/jpeg']
 where id = 'tp-task-photos';
